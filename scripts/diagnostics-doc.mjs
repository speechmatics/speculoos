/**
 * Generates docs/DIAGNOSTICS.md from the catalogue in @speculoos/core.
 *
 * The catalogue is the source of truth because a test checks it against what
 * is actually emitted. Writing the table by hand would give it a second,
 * unchecked source that quietly disagrees.
 *
 *   node scripts/diagnostics-doc.mjs           # write
 *   node scripts/diagnostics-doc.mjs --check   # fail if stale (for CI)
 */
import { readFile, writeFile } from "node:fs/promises";
import { DIAGNOSTIC_CODES } from "@speculoos/core";

const ORDER = { error: 0, warning: 1, info: 2 };
const sorted = [...DIAGNOSTIC_CODES].sort(
  (a, b) => ORDER[a.severity] - ORDER[b.severity] || a.code.localeCompare(b.code),
);

const rows = sorted
  .map((d) => `| \`${d.code}\` | ${d.severity} | \`${d.source}\` | ${d.meaning} |`)
  .join("\n");

const counts = Object.entries(
  sorted.reduce((acc, d) => ({ ...acc, [d.severity]: (acc[d.severity] ?? 0) + 1 }), {}),
)
  .map(([k, v]) => `${v} ${k}`)
  .join(", ");

const doc = `# Diagnostic codes

<!-- Generated by scripts/diagnostics-doc.mjs. Edit packages/core/src/diagnostics.ts. -->

Every diagnostic Speculoos emits carries a stable \`code\`. Codes are a public
contract: they end up in CI configuration through \`speculoos lint --allow\`, so
renaming one breaks somebody's build.

${sorted.length} codes in total — ${counts}.

\`\`\`sh
speculoos lint spec.yaml --allow NOT,IF --max-severity error
\`\`\`

\`lint\` exits non-zero when any diagnostic at or above \`--max-severity\`
(default \`warning\`) survives the allow-list. An \`--allow\` entry that is not a
known code is reported as a warning rather than silently ignored.

| Code | Severity | Emitted by | Meaning |
|---|---|---|---|
${rows}

## Unsupported keywords

Six of the codes above are generated from a JSON Schema keyword rather than
written out. \`lower\` strips a leading \`$\` and converts camelCase to
SCREAMING_SNAKE_CASE, so \`if\` becomes \`IF\` and \`$dynamicRef\` becomes
\`DYNAMIC_REF\`.

They all mean the same thing: the keyword constrains *validation* in a way that
has no display form. The node renders as \`unsupported\` with the reason
attached, and whatever else the schema said still renders — a field is never
dropped silently.

## Reading them in code

\`\`\`ts
import { DIAGNOSTIC_CODES, describeDiagnostic } from "@speculoos/core";

describeDiagnostic("ALLOF_CONFLICT")?.severity; // "warning"
\`\`\`
`;

const path = new URL("../docs/DIAGNOSTICS.md", import.meta.url);
if (process.argv.includes("--check")) {
  const current = await readFile(path, "utf8").catch(() => "");
  if (current !== doc) {
    console.error("docs/DIAGNOSTICS.md is stale — run `pnpm docs:diagnostics`.");
    process.exit(1);
  }
  console.log("docs/DIAGNOSTICS.md is up to date.");
} else {
  await writeFile(path, doc);
  console.log(`wrote docs/DIAGNOSTICS.md (${sorted.length} codes)`);
}
